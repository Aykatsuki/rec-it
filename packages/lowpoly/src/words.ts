/** The words of a text, lower-case, with simple plurals and -ing/-ed forms reduced. */
export function wordList(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/[’']/g, '')
    .split(/[^a-z0-9-]+/)
    .filter(Boolean);
}

function stems(w: string): string[] {
  const out = [w];
  if (w.endsWith('ies') && w.length > 4) out.push(`${w.slice(0, -3)}y`);
  if (w.endsWith('es') && w.length > 3) out.push(w.slice(0, -2));
  if (w.endsWith('s') && w.length > 3) out.push(w.slice(0, -1));
  if (w.endsWith('ing') && w.length > 5)
    out.push(w.slice(0, -3), `${w.slice(0, -3)}e`, w.slice(0, -4));
  if (w.endsWith('ed') && w.length > 4) out.push(w.slice(0, -2), w.slice(0, -1), w.slice(0, -3));
  return out;
}

/**
 * Values the text mentions, in order of first mention (two-word phrases before single words).
 * "He hid in the jungle and ate bananas" → for PROP_WORDS: ['banana'].
 */
export function mentions(text: string, table: Record<string, string>): string[] {
  const ws = wordList(text);
  const found: { at: number; value: string }[] = [];
  for (let i = 0; i < ws.length; i++) {
    const pair = i + 1 < ws.length ? `${ws[i]} ${ws[i + 1]}` : '';
    const pairHit =
      pair &&
      (table[pair] ??
        stems(ws[i + 1]!)
          .map((s) => table[`${ws[i]} ${s}`])
          .find(Boolean));
    if (pairHit) {
      found.push({ at: i, value: pairHit });
      continue;
    }
    const hit = stems(ws[i]!)
      .map((s) => table[s])
      .find(Boolean);
    if (hit) found.push({ at: i, value: hit });
  }
  const seen = new Set<string>();
  return found
    .sort((a, b) => a.at - b.at)
    .map((f) => f.value)
    .filter((v) => (seen.has(v) ? false : (seen.add(v), true)));
}

/** The first value the text mentions, if any. */
export function firstMention(text: string, table: Record<string, string>): string | undefined {
  return mentions(text, table)[0];
}

/** Whether a script talks to the viewer ("you") more than about someone ("he", "she"). */
export function secondPerson(script: string): boolean {
  const ws = wordList(script);
  const you = ws.filter(
    (w) => w === 'you' || w === 'your' || w === 'youre' || w === 'yourself',
  ).length;
  const them = ws.filter((w) => ['he', 'she', 'his', 'her', 'him', 'they'].includes(w)).length;
  return you >= them;
}
